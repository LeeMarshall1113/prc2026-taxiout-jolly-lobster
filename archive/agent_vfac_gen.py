"""Generates scripts/agent_vfac_{bxnest,fold4,bxserve,serve}.py from the etrs copies by exact-text replacement (each anchor must match once)."""
import re
S="archive/"
def sub(txt, old, new, cnt=1):
    assert txt.count(old)==cnt, (old[:60], txt.count(old)); return txt.replace(old,new)
HEAD='"""experiment vfac {n}: generated by archive/agent_vfac_gen.py from archive/agent_etrs_{n}.py (ET hook replaced by the vfac variant hook,\nscripts/agent_vfac_models.py; per-fold checkpoints). docs/LAB-NOTES.md. Original docstring follows.\n'
FOLD_LOOP="""    for vn in VN:
        ckp = f"{args.ckpt_dir}/{args.tag}_{vn}_f{k}.npy" if args.ckpt_dir else ""
        if ckp and os.path.exists(ckp):
            ADDS[vn][te] = np.load(ckp); continue
        rec = V.alt_recipe(vn, RECIPE)
        Xv = X if rec == RECIPE else FEAT(rk, fin, rec)
        ADDS[vn][te] = V.fit_predict(vn, rec, Xv[~te], t[~te], fin[~te], Xv[te], fin[te], args.seed, R)
        if ckp:
            np.save(ckp + ".tmp.npy", ADDS[vn][te]); os.replace(ckp + ".tmp.npy", ckp)
        if Xv is not X: del Xv
        log(f"fold {k} variant {vn} done")
"""
# ---------------- bxnest
t=open(S+"agent_etrs_bxnest.py",encoding="utf-8").read()
t=HEAD.format(n="bxnest")+t.split('"""',2)[2].join(["",""]) if False else t
t=t.replace('"""experiment sb2 bxnest','"""experiment vfac bxnest (generated, see archive/agent_vfac_gen.py; variant hook archive/agent_vfac_models.py)\n\nexperiment sb2 bxnest',1)
t=sub(t,"from archive.agent_sb2_restack import features, fit, load_rows, parse, predict\n","from archive.agent_sb2_restack import features, fit, load_rows, parse, predict\nimport archive.agent_sb2_restack as R\nimport archive.agent_vfac_models as V\nFEAT = features\n")
t=sub(t,'ap.add_argument("--nov-fold"','ap.add_argument("--variants", default="ctrl")\nap.add_argument("--ckpt-dir", default="")\nap.add_argument("--tag", default="x")\nap.add_argument("--nov-fold"')
t=sub(t,"args = ap.parse_args()\n","args = ap.parse_args()\nVN = args.variants.split(',')\nassert not {'unc','nov'} & set(args.recipe.split(',')), 'unc/nov not supported by the vfac hook'\n")
t=sub(t,"add = np.zeros(len(t))\nadd_e = np.zeros(len(t))\n","ADDS = {vn: np.zeros(len(t)) for vn in VN}\n")
old=t[t.index("    add[te] = predict(fit("):t.index("    del X, rk\n")]
t=t.replace(old,FOLD_LOOP)
t=t.replace("    log(f\"outer fold {k} done; training-row bx_g changed rms \"\n        f\"{np.sqrt(np.nanmean((bg[~te & has] - bxg0[~te & has]) ** 2)):.1f} s\")","    log(f\"outer fold {k} done\")")
tail_start=t.index('new = Z["both_guard"].astype(float).copy()')
cache_blk=t[t.index("if cache is None:\n    np.savez(args.cols"):t.index("N = len(Z")]
t=t[:tail_start]+'np.savez(args.out, ids=rid, fin=fin, y=y, apt=apt, days=d_npz, **{f"add_{vn}": ADDS[vn] for vn in VN})\n'+cache_blk+'log(f"vfac bxnest {args.recipe} variants {VN} seed {args.seed} -> {args.out}")\n'
open(S+"agent_vfac_bxnest.py","w",encoding="utf-8").write(t)
# ---------------- fold4
t=open(S+"agent_etrs_fold4.py",encoding="utf-8").read()
t=t.replace('"""experiment sb2 fold4','"""experiment vfac fold4 (generated, see archive/agent_vfac_gen.py; variant hook archive/agent_vfac_models.py)\n\nexperiment sb2 fold4',1)
t=sub(t,"from archive.agent_sb2_restack4 import features, fit, load_rows, parse, predict\n","from archive.agent_sb2_restack4 import features, fit, load_rows, parse, predict\nimport archive.agent_sb2_restack4 as R\nimport archive.agent_vfac_models as V\nimport os\n")
t=sub(t,'ap.add_argument("--nov-fold"','ap.add_argument("--variants", default="ctrl")\nap.add_argument("--ckpt-dir", default="")\nap.add_argument("--tag", default="x")\nap.add_argument("--nov-fold"')
t=sub(t,"a = ap.parse_args()\n","a = ap.parse_args()\nVN = a.variants.split(',')\nassert not {'unc','nov'} & set(a.recipe.split(',')), 'unc/nov not supported by the vfac hook'\n")
t=sub(t,"add = np.zeros(len(t))\nadd_e = np.zeros(len(t))\n","ADDS = {vn: np.zeros(len(t)) for vn in VN}\n")
loop=FOLD_LOOP.replace("args.","a.").replace("RECIPE","a.recipe").replace("FEAT(rk, fin, rec)","features(r, fin, rec)").replace("log(","print(")
i0=t.index("        add[te] = predict(fit("); i1=t.index("        if cb and k == 0")
loop="\n".join(("    "+l if l.strip() else l) for l in loop.split("\n"))
t=t[:i0]+loop+"\n"+t[i1:]
t=t.replace("        if cb and k == 0 and time.time() - t1 > a.cb_guard_s:","        if False:")
tail=t.index('new = Z[a.blend].astype(float).copy()')
t=t[:tail]+'np.savez(a.out, ids=RID0[pos >= 0] if False else r["MVT_ID_mvt"].to_numpy(), fin=fin, y=y, apt=np.asarray(r["apt"].to_list()), days=d_npz, **{f"add_{vn}": ADDS[vn] for vn in VN})\nprint(f"vfac fold4 {a.recipe} variants {VN} seed {a.seed} -> {a.out} {time.time() - T0:.0f}s")\n'
open(S+"agent_vfac_fold4.py","w",encoding="utf-8").write(t)
# ---------------- serves
SERVE_TAIL='''_SB2W = sb2_weights(tr, _SB2T)
assert not {"unc", "nov"} & _SB2T, "unc/nov not supported by the vfac hook"
import archive.agent_vfac_models as V
VN = a.variants.split(",")
JS = []
for _inp in a.inp.split(","):
    sub = pl.read_parquet(_inp)
    assert sub[ID].n_unique() == sub.height
    r26 = load_2026(a.rows_2026)
    JS.append(r26.join(sub.select(C(ID).cast(pl.Float64), C(T).cast(pl.Float64).alias("_fin")), on=ID, how="inner"))
OUT = {}
for si, j in enumerate(JS):
    OUT[f"ids_{si}"] = j[ID].to_numpy(); OUT[f"apt_{si}"] = np.asarray(j["apt"].to_list()); OUT[f"fin_{si}"] = j["_fin"].to_numpy()
ytr_ = z["y"][pos].astype(float) - fin_tr
fin_all = np.concatenate([j["_fin"].to_numpy() for j in JS])
for vn in VN:
    rec = V.alt_recipe(vn, a.recipe)
    Xtr_ = R3.features(tr, fin_tr, rec)
    Xte_ = np.vstack([R3.features(j, j["_fin"].to_numpy(), rec) for j in JS])
    ad = V.fit_predict(vn, rec, Xtr_, ytr_, fin_tr, Xte_, fin_all, a.seed, R3)
    del Xtr_, Xte_
    o = 0
    for si, j in enumerate(JS):
        OUT[f"add_{vn}_{si}"] = ad[o:o + j.height]; o += j.height
    print(f"variant {vn} fitted+served ({time.time() - T0:.0f}s)", flush=True)
    np.savez(a.out + ".tmp.npz", **OUT); import os as _o; _o.replace(a.out + ".tmp.npz", a.out)
print(f"vfac serve {a.recipe} variants {VN} streams {len(JS)} -> {a.out} ({time.time() - T0:.0f}s)")
'''
for n in ("bxserve","serve"):
    t=open(S+f"agent_etrs_{n}.py",encoding="utf-8").read()
    t=t.replace('"""experiment sb2 serve',f'"""agent vfac {n} (generated, see archive/agent_vfac_gen.py; variant hook archive/agent_vfac_models.py; writes ADD arrays per stream/variant to one npz)\n\nexperiment sb2 serve',1)
    t=sub(t,'ap.add_argument("--nov-train"','ap.add_argument("--variants", default="ctrl")\nap.add_argument("--nov-train"')
    i=t.index("_SB2W = sb2_weights(tr, _SB2T)")
    t=t[:i]+SERVE_TAIL
    open(S+f"agent_vfac_{n}.py","w",encoding="utf-8").write(t)
print("generated")
