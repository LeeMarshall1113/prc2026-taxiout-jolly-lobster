"""Generate the SERVING-ANALOGUE re-stack copies (docs/LAB-NOTES.md, amendment A2) by exact string patches
of the PRODUCTION osm code path (smallbundle2 C6 = v129+: archive/agent_sb2_bxnest.py / agent_sb2_fold4.py):
  archive/agent_bulkr_sb2bxnest.py = archive/agent_sb2_bxnest.py + --apply-fin-npz
  archive/agent_bulkr_sb2fold4.py  = archive/agent_sb2_fold4.py  + --apply-fin-npz
--apply-fin-npz P: every outer fold's model is TRAINED on --fin-npz's stage output (old chain) and each held-out row is
PREDICTED from P's stage output (serving-analogue chain); written both_guard = max(fin_apply + add, 0), npz base = P.
With --apply-fin-npz "" each copy is its source bit for bit. (The earlier md-based copies agent_bulkr_bxnest.py /
agent_bulkr_fold4.py are superseded and unused.)
"""
from pathlib import Path


def patch(src, dst, subs):
    s = Path(src).read_text(encoding="utf-8")
    for old, new in subs:
        assert s.count(old) == 1, (dst, s.count(old), old[:70])
        s = s.replace(old, new)
    Path(dst).write_bytes(s.encode("utf-8"))
    print("wrote", dst)


HEAD = ('"""experiment bulkr COPY (docs/LAB-NOTES.md A2; generated by archive/agent_bulkr_make_restack.py): adds\n'
        '--apply-fin-npz (train on --fin-npz, predict held-out rows from the apply npz). Original docstring follows.\n\n')


def first_line(path):
    return Path(path).read_text(encoding="utf-8").split("\n", 1)[0]


APPLY_LOAD = ('    assert np.array_equal(za["ids"].astype(float), ids), "apply npz: ids / order differ from --fin-npz"\n'
              '    assert np.array_equal(za["y"], Z["y"]), "apply npz: y differs"\n')

f0 = first_line("archive/agent_sb2_bxnest.py")
patch("archive/agent_sb2_bxnest.py", "archive/agent_bulkr_sb2bxnest.py", [
    (f0, HEAD + f0[3:]),
    ('ap.add_argument("--unc-npz", default="")', 'ap.add_argument("--unc-npz", default="")\nap.add_argument("--apply-fin-npz", default="")'),
    ('fin = Z["both_guard"][pos].astype(float)\n',
     'fin = Z["both_guard"][pos].astype(float)\nfin_app = fin\nif args.apply_fin_npz:\n'
     '    za = np.load(args.apply_fin_npz, allow_pickle=True)\n' + APPLY_LOAD +
     '    fin_app = za["both_guard"][pos].astype(float)\n'
     '    log(f"apply fin {args.apply_fin_npz}: rms(apply - train fin) {np.sqrt(((fin_app - fin) ** 2).mean()):.2f} s")\n'),
    ('    add[te] = predict(fit(X[~te], t[~te], RECIPE, args.seed, w=None if WALL is None else WALL[~te]), X[te])\n',
     '    XA = features(rk, fin_app, RECIPE) if args.apply_fin_npz else X\n'
     '    add[te] = predict(fit(X[~te], t[~te], RECIPE, args.seed, w=None if WALL is None else WALL[~te]), XA[te])\n'
     '    del XA\n'),
    ('new = Z["both_guard"].astype(float).copy()\nnew[pos] = np.maximum(fin + add, 0.0)\n',
     'if args.apply_fin_npz:\n    Z = {k: za[k] for k in za.keys()}\n'
     'new = Z["both_guard"].astype(float).copy()\nnew[pos] = np.maximum(fin_app + add, 0.0)\n'),
])

