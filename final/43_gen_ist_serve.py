"""Generate final/ist_corrector_serve.py from archive/agent_istnext_04_serve.py (the serving script of the Istanbul corrector with the
nine-airport column lists, design D1, and of the shipped Istanbul views term with --cols none).

Only the serve-side file names change: everything the shipped script reads for the 2026 rows now comes from the directory env
FINAL_IST_SERVE (written by final/43_ist_serve_inputs.py): rank features, keys file, plan-clock columns, handover columns; the chain value
before any corrector is the parquet env FINAL_IST_BASE (final/43_ist_build.py output); the views members are read from env FINAL_LV_DIR
(files ltfmm_ctrl_srv_99_98_<kind>.npz, ltfmm_treat_srv_99_98_<member>.npz of final/ist_lv_members.py); the take-off times come from
env FINAL_RANKING. The comparison with the shipped January/July term at the end is dropped. Shipped arguments:
    --arm AQCEHSBR --keys agent_lv_keys8.npz --cfg S2 --k 1.0 --anom A --seeds 0,1,2 --cols D1 --out <name>
(--olddelta and --base are read by the shipped script; pass any existing file, they are not used for the served rows.)
Writes <FINAL_IST_SERVE>/<name>_term.npz (sid, d = served term at k, snow_serve, names, NEWF, NEWS).
    python final/43_gen_ist_serve.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE.parent / "archive" / "agent_istnext_04_serve.py").read_text(encoding="utf-8").replace("\r\n", "\n")
NL = chr(10)


def sub(old, new, count=1):
    global t
    assert t.count(old) >= 1, old[:70]
    t = t.replace(old, new) if count == 0 else t.replace(old, new, count)


sub("import argparse", "import argparse" + NL + "import os" + NL + "from pathlib import Path as _P" + NL
    + "_SD = _P(os.environ['FINAL_IST_SERVE'])" + NL + "_BASE = os.environ['FINAL_IST_BASE']" + NL + "_RANK = os.environ['FINAL_RANKING']")
sub("import agent_lv_views as VW  # noqa: E402", "import agent_lv_views as VW  # noqa: E402" + NL + "VW.load_serve.__defaults__ = (os.environ['FINAL_LV_DIR'],)")
sub('K = np.load(I + a.keys, allow_pickle=True)', 'K = np.load(_SD / a.keys, allow_pickle=True)')
sub('base = pl.read_parquet(I + "v137_ltfmsnow_final.parquet").sort(ID)', 'base = pl.read_parquet(_BASE).with_columns(C(ID).cast(pl.Float64)).sort(ID)')
sub('rl = pl.read_parquet(I + "agent_bndl_rank_ltfm.parquet").join(', 'rl = pl.read_parquet(_SD / "rank_ltfm.parquet").join(')
sub('v129n = pl.read_parquet(I + "agent_combo_v129_noM4_final.parquet").sort(ID)', 'v129n = base')
sub('HO = np.load(I + "agent_lv_handover.npz", allow_pickle=True)', 'HO = np.load(_SD / "agent_lv_handover.npz", allow_pickle=True)')
sub('ZC = np.load(I + "agent_istpcd_cols.npz", allow_pickle=True)', 'ZC = np.load(_SD / "agent_istpcd_cols.npz", allow_pickle=True)')
sub('rk = pl.read_parquet("data/raw/ranking.parquet", columns=[ID, "MVT_TIME_UTC_mvt"])', 'rk = pl.read_parquet(_RANK, columns=[ID, "MVT_TIME_UTC_mvt"]).with_columns(C(ID).cast(pl.Float64))')
sub('np.savez(I + a.out + "_catmap.npz"', 'np.savez(_SD / (a.out + "_catmap.npz")')
sub('np.savez(I + a.out + "_term.npz"', 'np.savez(_SD / (a.out + "_term.npz")')
i = t.index('_o = np.load(I + "agent_lv4r_ltfm_final_delta.npz"')
j = t.index('print("wrote", a.out + "_term.npz")')
t = t[:i] + t[j:]
hdr = '"""GENERATED by final/43_gen_ist_serve.py from archive/agent_istnext_04_serve.py; see that generator for the changes."""' + NL
body = t.split('"""', 2)[2]
(HERE / "ist_corrector_serve.py").write_text(hdr + body, encoding="utf-8")
print("wrote final/ist_corrector_serve.py")
