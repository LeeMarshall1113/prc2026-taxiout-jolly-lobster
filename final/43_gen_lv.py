"""Generate final/ist_lv_members.py from archive/agent_lv_members.py (the Istanbul views members, serve mode only).

Only the two reads of the ranking file change: the served frame is built one calendar month at a time from the file named by env
FINAL_RANKING, months env FINAL_MONTHS (default 2,6), and the sequence-feature frame keeps those months. Serve checkpoints are
tagged by --tag exactly as in the shipped run (use ltfmmF_ctrl_srv / ltfmmF_treat_srv so the shipped January/July files in
results/ltfmm are not mixed up). Arms to run: ctrl (--ltfm-seq off, quantiles q10,q50,q90) and treat (--ltfm-seq on).
    python final/43_gen_lv.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE.parent / "archive" / "agent_lv_members.py").read_text(encoding="utf-8").replace("\r\n", "\n")
NL = chr(10)
old_path = "sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))"
assert old_path in t
t = t.replace(old_path, old_path + NL + "sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir, 'archive'))"
              + NL + "_RANKING = Path(os.environ['FINAL_RANKING'])" + NL + "_MONTHS = [int(s) for s in os.environ.get('FINAL_MONTHS', '2,6').split(',')]", 1)
old1 = 'RANK = feat_build(pl.read_parquet(RAW_DIR / "ranking.parquet"), with_target=False)'
new1 = ('RANK = pl.concat([feat_build(pl.scan_parquet(_RANKING).filter(pl.col("MVT_TIME_UTC_mvt").dt.month() == _m).collect(), with_target=False)'
        ' for _m in _MONTHS])')
old2 = 'r26 = pl.scan_parquet(RAW_DIR / "ranking.parquet").select(COLS).filter(ltfm).collect()'
new2 = 'r26 = pl.scan_parquet(_RANKING).select(COLS).filter(ltfm).collect().filter(pl.col("MVT_TIME_UTC_mvt").dt.month().is_in(_MONTHS))'
assert old1 in t and old2 in t
t = t.replace(old1, new1).replace(old2, new2)
assert 'RAW_DIR / "ranking.parquet"' not in t
hdr = '"""GENERATED by final/43_gen_lv.py from archive/agent_lv_members.py; see that file. Needs env FINAL_RANKING and FINAL_MONTHS."""' + NL
body = t.split('"""', 2)[2]
(HERE / "ist_lv_members.py").write_text(hdr + body, encoding="utf-8")
print("wrote final/ist_lv_members.py")
